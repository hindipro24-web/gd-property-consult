function safeMapDestination(property = {}) {
  const savedLink = String(property.mapEmbedUrl || "").trim();

  if (savedLink) {
    try {
      const parsed = new URL(savedLink, window.location.href);
      if (parsed.protocol === "https:" || parsed.protocol === "http:") {
        return parsed.href;
      }
    } catch (error) {
      console.warn("Invalid Google Maps location link", error);
    }
  }

  if (property.latitude != null && property.longitude != null) {
    return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(`${property.latitude},${property.longitude}`)}`;
  }

  const locationText = property.mapLabel || property.location || "";
  return locationText
    ? `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(locationText)}`
    : "";
}

function openPropertyMapLocation() {
  const mapBox = byId("propertyMapBox");
  const destination = mapBox?.dataset.mapDestination;
  if (!destination) return;

  const opened = window.open(destination, "_blank", "noopener,noreferrer");
  if (opened) opened.opener = null;
}

function professionalStatus(value = "") {
  const status = String(value || "").trim();
  if (/^move\s*to\s*go$/i.test(status)) return "Ready to move";
  return status || "Available";
}

function professionalPrice(property, configuration = null) {
  const purpose = property?.listing_purpose === "Rent" ? "Rent" : "Sale";
  const label = String(configuration?.price_label || property?.price_label || "").trim();
  const amount = Number(configuration?.price_amount || property?.price_amount || 0);
  const invalidRentalPrice = purpose === "Rent" && (amount >= 1000000 || /\b(?:cr|crore|lakh|lac)\b/i.test(label));
  return invalidRentalPrice ? "Rent on request" : (label || "On request");
}

