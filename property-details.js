async function loadProperty() {
  if (requestedId && window.isSupabaseConfigured?.() && window.supabase) {
    try {
      const client = window.KeyAssetsSupabaseClient || window.supabase.createClient(window.KEYASSETS_SUPABASE_URL, window.KEYASSETS_SUPABASE_ANON_KEY);
      window.KeyAssetsSupabaseClient = client;
      const { data, error } = await client.from("properties").select("*").eq("id", requestedId).single();
      if (!error && data) {
        const normalized = normalizeSupabaseProperty(data);
        renderProperty(normalized.name, normalized);
        return;
      }
      console.warn("Could not load property from Supabase; fallback data used.", error?.message);
    } catch (error) {
      console.warn("Property connection failed; fallback data used.", error);
    }
  }

  const name = requestedName && FALLBACK_PROPERTIES[requestedName] ? requestedName : defaultName;
  const fallback = FALLBACK_PROPERTIES[name];
  fallback.configurations = Array.isArray(fallback.configurations) ? fallback.configurations : [];
  renderProperty(name, fallback);
}

